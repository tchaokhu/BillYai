/**
 * เซสชันบนหน้าจอ LIFF ใช้ไม่ได้ — พา login ใหม่ หรือแสดงข้อความแล้วจบ
 *
 * แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะกฎนี้ผิดแล้วเจ็บสองทาง: ตัดสินแคบไปแปลว่า
 * ผู้ใช้ตันโดยไม่มีทางกดต่อ ส่วนกว้างไปแปลว่า redirect วนไม่จบจนไม่มีข้อความไหน
 * ถูกอ่านสักครั้ง · ทั้งสองอย่างมองไม่เห็นจาก JSX
 */

/**
 * `alreadyTried` = แท็บนี้พา login ใหม่ไปแล้วหนึ่งรอบ
 *
 * **ครั้งเดียวต่อแท็บ** — `liff.getIDToken()` คืน token ใบที่ได้ตอน login และไม่
 * รีเฟรชให้ ส่วน `liff.isLoggedIn()` ยังเป็น `true` หลัง token หมดอายุ · หนึ่งรอบ
 * จึงแก้เคสที่พบจริง (เปิดค้างไว้ข้ามชั่วโมง) ส่วนรอบที่สองที่ยังไม่ผ่านแปลว่า
 * เหตุอยู่ที่การตั้งค่า ไม่ใช่ที่เซสชัน — ตรงนั้นต้องให้เขาเห็นข้อความ
 */
export function shouldRelogin(problem: string | undefined, alreadyTried: boolean): boolean {
  if (alreadyTried) return false
  return problem === 'no-id-token' || problem === 'unauthenticated'
}
