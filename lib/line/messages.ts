/**
 * แปลง `ReplyPlan` เป็น message object ของ LINE — **ข้อความไทยทั้งระบบอยู่ไฟล์นี้**
 *
 * **ไกด์ต้องไม่โฆษณาคำสั่งที่ยังไม่มี** — กติกานี้บังคับด้วยเทสต์ใน
 * `messages.test.ts` ที่ผูกข้อความไกด์เข้ากับ `IMPLEMENTED_COMMANDS` โดยตรง
 * เพิ่มคำสั่งเข้ารายการนั้นเมื่อไหร่ เทสต์จะแดงจนกว่าไกด์จะพูดถึงมัน
 */

import { IMPLEMENTED_COMMANDS, type ReplyPlan, type Surface } from '../flow/dispatch'
import { formatSatang } from '../money'
import type { BotCommand } from '../types'
import type { LineFlexMessage, QuickReplyItem } from './flex'

/** text message ของ LINE — ยาวได้ 5000 ตัวอักษร */
export interface LineTextMessage {
  type: 'text'
  text: string
  /**
   * **postback ติดกับข้อความธรรมดาได้ทางนี้** — ซึ่งเป็นสิ่งเดียวที่ทำให้การ์ดที่
   * ลดรูปเป็นข้อความยังกดยืนยันได้ · ข้อความที่กดไม่ได้เท่ากับไม่มีการ์ด
   */
  quickReply?: { items: QuickReplyItem[] }
}

export type LineMessage = LineTextMessage | LineFlexMessage

function text(value: string): LineTextMessage[] {
  return [{ type: 'text', text: value }]
}

/**
 * ไวยากรณ์ของคำสั่งที่เปิดใช้แล้ว
 *
 * `IMPLEMENTED_COMMANDS` เป็นแหล่งเดียวว่าอะไรเปิดแล้ว บรรทัดที่นี่เป็นแค่
 * "ถ้าเปิดแล้วจะอธิบายว่ายังไง" · เทสต์บังคับให้สองอย่างนี้ตรงกันเสมอ
 */
const COMMAND_HELP: ReadonlyArray<{ command: BotCommand; line: string }> = [
  { command: 'balance', line: 'ยอด — สรุปว่าใครติดใครเท่าไหร่ · ใส่ #แท็ก ต่อท้ายเพื่อดูเฉพาะทริปนั้น' },
  { command: 'bills', line: 'บิล — รายการบิลที่จดไว้ กดดูรายละเอียดได้' },
  { command: 'nudge', line: 'ทวง — การ์ดทวงพร้อม QR ยอดเป๊ะ' },
  { command: 'edit', line: 'แก้ — เปิดหน้าจัดการบิล' },
  { command: 'undo', line: 'เลิก — ยกเลิกคำสั่งล่าสุดของตัวเอง' },
]

/** ชื่อที่คนพิมพ์เวลาเรียกบอทในกลุ่ม — ใช้ตอนบอกให้เขาพิมพ์คำสั่ง ไม่ใช่ตัวตัดสินว่าถูกเรียก */
const MENTION = '@บิลใหญ่'

/**
 * คำสั่งที่จะบอกให้เขาพิมพ์ — **เติม `@บิลใหญ่` ให้เองเมื่ออยู่ในกลุ่ม**
 *
 * ในกลุ่มคีย์เวิร์ดเปล่าๆ ตกเป็นความเงียบตาม D47 · บอกให้พิมพ์ `บิล` เฉยๆ จึงส่งคน
 * ไปเจอความเงียบ ซึ่งอ่านออกได้อย่างเดียวว่าบอทพัง · 1:1 ใส่ไม่ได้เพราะ LINE ไม่มี
 * mention ที่นั่น ข้อความจะไม่ถูกตัดแล้วตกเป็น `unparsed`
 */
function typeThis(command: string, surface: Surface): string {
  return surface === 'group' ? `${MENTION} ${command}` : command
}

/**
 * ชื่อแท็กที่จะเอาไปแปะในข้อความ — **ตัดความยาว** เกณฑ์เดียวกับที่การ์ดทำ
 *
 * `parseCommand` รับ token ที่ขึ้นต้นด้วย `#` ยาวเท่าไหร่ก็ได้ และ `event_tag` เป็น
 * `text` ไม่มีเพดาน · แท็กยาวๆ ทำให้ข้อความทะลุ 5000 ตัวอักษรแล้ว LINE ปฏิเสธ
 * ทั้ง reply — คนถามจะไม่ได้คำตอบอะไรเลย
 */
const MAX_TAG = 24

function tagLabel(tag: string): string {
  return tag.length <= MAX_TAG ? `#${tag}` : `#${tag.slice(0, MAX_TAG - 1)}…`
}

/**
 * ไกด์ — สอนเฉพาะของที่ใช้ได้จริงในเฟสนี้ **และในที่ที่คนอ่านอยู่**
 *
 * สอนไวยากรณ์ที่ยังใช้ไม่ได้คือการหลอกให้คนพิมพ์แล้วโดนปฏิเสธ ซึ่งแย่กว่าบอกตรงๆ
 * ว่ายังไม่พร้อม · ท่อนคำสั่งโตเองตาม `IMPLEMENTED_COMMANDS`
 *
 * **ท่อนคำสั่งต่างกันตาม surface ตั้งแต่ D47** — ในกลุ่มคีย์เวิร์ดเปล่าๆ ตกเป็น
 * ความเงียบ ไกด์ที่สอนรูปเปล่าจึงหลอกให้คนคิดว่าบอทพัง · ส่วนใน 1:1 จะใส่
 * `@บิลใหญ่` ให้ไม่ได้เลย เพราะ LINE ไม่มี mention ที่นั่น ข้อความจะไม่ถูกตัด
 * แล้วตกเป็น `unparsed` ซึ่งใน 1:1 ตอบไกด์ = วนกลับมาที่เดิมไม่รู้จบ
 *
 * **ท่อนจดบิลเหมือนกันทั้งสองที่** — `+` ไม่ถูก D47 แตะ (D19)
 */
function buildGuide(surface: Surface): string {
  const prefix = surface === 'group' ? `${MENTION} ` : ''
  return [
    'บิลใหญ่ช่วยจดว่าใครจ่ายอะไรไปเท่าไหร่ แล้วคำนวณให้ว่าใครติดใครเท่าไหร่',
    '',
    'จดบิลด้วยการพิมพ์:',
    '  + ข้าว 1200 กอล์ฟ ตูน',
    '  + คอนโด 8000 กอล์ฟx2 เบียร์ ตูน',
    '  + เหล้า 900 กอล์ฟ ตูน รวมฉัน',
    '  + ข้าว 1200 #เชียงใหม่',
    '',
    'ยอดที่พิมพ์คือยอดสุดท้ายที่จ่ายจริง รวมค่าบริการและ VAT แล้ว',
    ...COMMAND_HELP.filter((help) => IMPLEMENTED_COMMANDS.has(help.command)).map(
      (help) => `  ${prefix}${help.line}`,
    ),
  ].join('\n')
}

/** คิดครั้งเดียวตอนโหลด — เนื้อไกด์เป็นค่าคงที่ของแต่ละ surface */
const GUIDE: Readonly<Record<Surface, string>> = {
  group: buildGuide('group'),
  direct: buildGuide('direct'),
}

/**
 * `draft` `balance` และ `bills` ไม่มีที่นี่โดยตั้งใจ — ทั้งสามต้องอ่าน DB ก่อนถึงจะ
 * รู้ว่าการ์ดหน้าตายังไง · ผู้เรียกไป I/O เองแล้วค่อยเรียกตัวสร้างการ์ดของมัน
 */
export function renderReply(
  plan: Exclude<ReplyPlan, { kind: 'draft' } | { kind: 'balance' } | { kind: 'bills' }>,
  /**
   * **บังคับส่ง ไม่มีค่าเริ่มต้น** — ไกด์เป็นข้อความเดียวที่ต่างกันตามที่ที่คนอ่าน
   * และค่าเริ่มต้นจะทำให้จุดเรียกที่ลืมส่งกลายเป็นไกด์ที่ผิดที่แบบเงียบๆ
   * ให้ตัว compiler ทวงดีกว่ารอไปเจอในแชทจริง
   */
  surface: Surface,
): LineTextMessage[] {
  switch (plan.kind) {
    case 'silent':
      // ไม่ส่งอะไรเลย — ต่างจากส่งข้อความว่าง ซึ่ง LINE จะปฏิเสธ
      return []
    case 'guide':
      return text(GUIDE[surface])
    case 'need-names':
      // ไวยากรณ์แปลว่า "หารเท่าทุกคนใน Roster" — วงนี้ยังไม่รู้จักใครเลยสักคน
      return text(
        'ยังไม่รู้จักใครในวงนี้เลย พิมพ์ชื่อคนที่หารด้วยมาด้วย เช่น\n  + ข้าว 1200 กอล์ฟ ตูน',
      )
    case 'unknown-sender':
      // ลองใหม่ไม่ช่วย — ต้องไปกดยอมรับข้อตกลงใน LINE ก่อน จึงต้องบอกให้ตรง
      return text(
        'จดให้ไม่ได้เพราะ LINE ไม่ได้บอกว่าใครเป็นคนพิมพ์ — ต้องยอมรับข้อตกลงการใช้งานบัญชีทางการก่อน แล้วพิมพ์ใหม่อีกครั้ง',
      )
    case 'committed':
      // ประกาศกลับเข้ากลุ่มเสมอ — ความโปร่งใสคือกลไกรักษาความปลอดภัยของระบบนี้ (D10)
      return text(`จดแล้ว: ${plan.description} ฿${formatSatang(plan.totalSatang)}`)
    case 'draft-gone':
      return text('การ์ดใบนี้ใช้ไม่ได้แล้ว พิมพ์บิลใหม่อีกครั้งได้เลย')
    case 'name-taken':
      return text(`ชื่อ "${plan.name}" มีเจ้าของแล้วในวงนี้ ลองเลือกชื่ออื่นหรือกด "ฉันเป็นคนใหม่"`)
    case 'name-in-bill':
      // ชื่อนี้ยังไม่มีเจ้าของ — มันแค่เป็นอีกแถวในบิลใบเดียวกัน ทางออกจึงคนละอย่าง
      return text(
        `"${plan.name}" อยู่ในบิลใบนี้อยู่แล้ว ถ้านั่นคือคุณ ให้กด "จดรายชิ้น" แล้วเอาชื่อนั้นออกจากบิลก่อน แล้วค่อยกดยืนยัน`,
      )
    case 'needs-identity':
      return text('เลือกชื่อของคุณจากปุ่มด้านล่างก่อน แล้วบิลจะถูกจดให้ทันที')
    case 'no-display-name':
      // ลองใหม่ไม่ช่วย — LINE ไม่ให้ชื่อมาจนกว่าเขาจะให้สิทธิ์
      return text('ยังดึงชื่อของคุณจาก LINE ไม่ได้ ลองเลือกชื่อที่มีอยู่แล้วในวงแทน')
    case 'settled':
      // ต่างจากวงที่ยังไม่เคยจดบิลซึ่งตอบไกด์ — คนนี้ใช้เป็นแล้ว ตอบไกด์ซ้ำคือ
      // ไม่ตอบคำถามที่เขาถาม
      return text('ตอนนี้ไม่มีใครติดใครแล้ว')
    case 'no-bills-for-tag':
      // เขาพิมพ์ชื่อแท็กมาเอง — สิ่งที่ผิดได้มากที่สุดคือพิมพ์ชื่อไม่ตรง
      return text(
        `ยังไม่มีบิลที่ติด ${tagLabel(plan.tag)} ในวงนี้ · พิมพ์ ${typeThis('บิล', surface)} เพื่อดูบิลที่จดไว้ได้`,
      )
    case 'settled-for-tag':
      /**
       * **ห้ามพูดว่า "ค้าง"** — การ์ดตามแท็กตอบไม่ได้ว่าเงินถูกจ่ายคืนไปแล้วหรือยัง
       * (D60) · ประโยคนี้พูดถึงการหารของบิล ไม่ใช่สถานะของเงิน
       */
      return text(`บิลของ ${tagLabel(plan.tag)} ไม่มีใครต้องจ่ายใคร`)
    case 'bill-not-found':
      // ตอบเหมือนกันทั้งกรณีบิลไม่มีจริงและกรณีอยู่คนละวง — การบอกว่า "มีอยู่แต่
      // ไม่ใช่ของวงนี้" คือการยืนยันการมีอยู่ของบิลในวงที่คนกดไม่ได้อยู่ด้วย
      return text(`หาบิลใบนี้ไม่เจอในวงนี้ พิมพ์ ${typeThis('บิล', surface)} เพื่อดูรายการล่าสุดได้`)
    case 'bill-voided':
      // เงียบไม่ได้ (อ่านออกว่าบอทพัง) และโชว์ยอดเก่าไม่ได้ (ตัวเลขผิดใน ledger)
      return text('บิลใบนี้ถูกยกเลิกไปแล้ว')
    case 'confirm-void':
      /**
       * **คำถาม ไม่ใช่การกระทำ** — quick reply ถือจังหวะที่สอง และหายไปเองเมื่อ
       * คนพิมพ์อย่างอื่นต่อ ซึ่งเป็นพฤติกรรมที่ถูกสำหรับปุ่มที่ไม่ควรค้างอยู่ในแชท
       */
      return [
        {
          type: 'text',
          text: [
            `ยกเลิกบิล ${plan.description} ฿${formatSatang(plan.totalSatang)} ใช่ไหม`,
            'ยอดของทุกคนในวงจะขยับตาม และบิลจะหายจากรายการ',
          ].join('\n'),
          quickReply: {
            items: [
              {
                type: 'action',
                action: {
                  type: 'postback',
                  label: 'ยกเลิกบิล',
                  data: `void=${plan.expenseId}&yes=1`,
                  displayText: 'ยกเลิกบิล',
                },
              },
            ],
          },
        },
      ]
    case 'bill-void-done':
      // ประกาศกลับเข้ากลุ่มเสมอ — audit ของ D11 คือสายตาของคนในวง ไม่ใช่ตาราง log
      return text(`ยกเลิกแล้ว: ${plan.description} ฿${formatSatang(plan.totalSatang)}`)
    case 'bill-void-not-allowed':
      /**
       * **ตอบ ไม่ใช่เงียบ** — ต่างจาก `not-yours` ของ D26 ที่เงียบเพื่อไม่ให้คนกด
       * ผิดเสียหน้า · ที่นี่เขากดมาสองจังหวะแล้ว และ `displayText` ของปุ่มพาคำว่า
       * `ยกเลิกบิล` ขึ้นในแชทในนามเขาไปเรียบร้อย · ความเงียบหลังจากนั้นอ่านออกได้
       * อย่างเดียวว่าบอทพัง ซึ่งแย่กว่าประโยคที่บอกว่าใครเป็นคนทำได้
       *
       * **ไม่อ้างรหัสการตัดสินใจในข้อความที่ผู้ใช้อ่าน** — `D11` เป็นของในเอกสาร
       */
      return text('ยกเลิกได้เฉพาะคนจดบิลกับคนจ่าย — ให้เขาเป็นคนกดนะ')
    case 'bill-void-needs-identity':
      // ทางออกอยู่ที่การ์ด Draft ใบถัดไป ซึ่งเป็นที่เดียวที่ claim ได้วันนี้
      return text(
        'ยังไม่รู้ว่าคุณเป็นใครในวงนี้ — จดบิลใบใหม่แล้วเลือกชื่อของคุณตอนกดยืนยันก่อน',
      )
    case 'not-available':
      return text('คำสั่งนี้ยังไม่เปิดใช้')
  }
}
