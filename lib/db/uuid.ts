/**
 * รูปของ uuid ตามที่คอลัมน์ `uuid` ของ Postgres รับ
 *
 * **ตัวพิมพ์ใหญ่ผ่านด้วย** — `uuid` ของ Postgres ไม่แคร์ตัวพิมพ์ ปฏิเสธที่นี่จะเข้ม
 * กว่าตัวจริงโดยไม่ได้อะไรกลับมา
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i

/**
 * ค่านี้เอาไปใส่ `where id = $1` ของคอลัมน์ uuid ได้ไหม
 *
 * **ด่านนี้มีไว้กัน 500 ไม่ใช่กันคนแปลกหน้า** — ค่าที่ไม่ใช่ uuid ไม่ได้ทำให้ query
 * "หาไม่เจอ" แต่ทำให้ Postgres โยน `invalid input syntax for type uuid` ซึ่งเดินทาง
 * ขึ้นไปเป็น 500 · id พวกนี้มาจาก postback ของการ์ดที่ลอยอยู่ในแชทได้ตลอดกาลและ
 * แก้ข้อความได้ ส่วน LINE ก็ยิง postback เดิมซ้ำเมื่อเจอ 500 — รวมกันแล้วเป็นลูปที่
 * ไม่มีใครได้คำตอบ · ตอบ "ไม่เจอ" คือคำตอบที่ถูกอยู่แล้ว: id ที่ไม่มีรูปของ uuid
 * ไม่มีทางตรงกับแถวไหนได้เลย
 */
export function isUuid(value: string): boolean {
  return UUID.test(value)
}
